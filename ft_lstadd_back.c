#include "libft.h"

void	ft_lstadd_back(t_list **lst, t_list *new)
{
	t_list	*last_node;

	if (!lst || !new)
		return ;
	if (*lst == NULL)
	{
		*lst = new;
		return ;
	}
	last_node = ft_lstlast(*lst);
	last_node->next = new;
}
// if list pointer doesnt exist, do nothing. same if no new node to add
// A if list is completely empty *lst is NULL
// new node becomes the head of the list
// B if list already has nodes
